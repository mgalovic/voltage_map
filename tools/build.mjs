// Build: embeds the department montages and inlines all CSS/JS into a single
// self-contained HTML file that runs offline from file:// (double-click).
//   node tools/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const APP = path.join(ROOT, 'app');
const require = createRequire(import.meta.url);
for (const f of ['00-core.js', '10-positions.js', '40-montage.js']) require(path.join(APP, 'src/js', f));
const EEG = globalThis.EEG;

// 1) department montages → JS data module
const dir = path.join(ROOT, 'montages');
const montages = [];
const warnings = [];
for (const f of fs.readdirSync(dir).filter((x) => x.toLowerCase().endsWith('.bqm')).sort()) {
  const txt = fs.readFileSync(path.join(dir, f), 'utf8').replace(/^﻿/, '');
  const r = EEG.montage.parseBQM(txt, f);
  montages.push(...r.montages);
  warnings.push(...r.warnings);
}
montages.sort((a, b) => a.order - b.order);
const mod = `/* Generated by tools/build.mjs from ${path.basename(dir)}/*.bqm — do not edit. */\n(function (G) {\n  G.EEG = G.EEG || {};\n  G.EEG.builtinMontages = ${JSON.stringify(montages)};\n})(typeof window !== 'undefined' ? window : globalThis);\n`;
fs.writeFileSync(path.join(APP, 'src/js/12-builtin-montages.js'), mod);
console.log(`montages: ${montages.length} (${montages.map((m) => m.name).join(', ')})`);
if (warnings.length) console.log('warnings:', warnings);

// 2) inline everything
let html = fs.readFileSync(path.join(APP, 'index.html'), 'utf8');
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, href) => `<style>\n${fs.readFileSync(path.join(APP, href), 'utf8')}</style>`);
const scripts = [];
html = html.replace(/<script src="([^"]+)"><\/script>\n?/g, (_, src) => {
  const code = fs.readFileSync(path.join(APP, src), 'utf8');
  if (/<\/script/i.test(code)) throw new Error(`${src} contains a closing script tag`);
  scripts.push(`/* ---- ${path.basename(src)} ---- */\n${code}`);
  return '';
});
const stamp = new Date().toISOString().slice(0, 16).replace('T', ' ');
html = html.replace('</body>', `<script>\n/* EEG Viewer — built ${stamp} */\n${scripts.join('\n')}\n</script>\n</body>`);
// EEG-Viewer.html: the file to keep locally (double-click); index.html: the same
// page served by GitHub Pages.
for (const name of ['EEG-Viewer.html', 'index.html']) fs.writeFileSync(path.join(ROOT, name), html);
console.log(`wrote EEG-Viewer.html and index.html (${(html.length / 1024).toFixed(0)} KB)`);
